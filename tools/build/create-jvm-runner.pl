use strict;
use warnings;
use 5.008;
use File::Spec;
use File::Copy 'cp';
use Cwd 'abs_path';

my $USAGE = "Usage: $0 <type> <basedir> <destdir> <prefix> <build-time-nqp-home> <nqp-home> <rakudo-home> <third party jars>\n";

my ($type, $basedir, $destdir, $prefix, $nqp_home, $static_nqp_home, $static_rakudo_home, $thirdpartyjars) = @ARGV
    or die $USAGE;

my $relocatable = $static_nqp_home eq '' && $static_rakudo_home eq '';

my $debugger = 0;
if ($type =~ /^(\w+)\-debug$/) {
    $type = $1;
    $debugger = 1;
}

die "Invalid target type $type" unless $type eq 'dev' || $type eq 'install';

my $cpsep     = $^O eq 'MSWin32' ? ';'    : ':';
my $bat       = $^O eq 'MSWin32' ? '.bat' : '';
my $nqplibdir = $^O eq 'MSWin32' ? File::Spec->catfile($static_nqp_home, 'lib') : File::Spec->catfile('${NQP_HOME}', 'lib');

my $nqpjars;
if ($^O eq 'MSWin32' || $type ne 'install') {
    $nqpjars = $thirdpartyjars;
}
else {
    # The following is a workaround turning the third-party JARS into relative
    # paths. The clean solution would be to pass in relative paths and only
    # prefix those with ${NQP_HOME} here.
    my @thirdpartyjars = map { abs_path($_) } split($cpsep, $thirdpartyjars);
    @thirdpartyjars    = map { $_ =~ s,$nqp_home,\${NQP_HOME},; $_ } @thirdpartyjars;
    $nqpjars           = join($cpsep, @thirdpartyjars);
}

my $bindir = $type eq 'install' ? File::Spec->catfile($prefix, 'bin') : $prefix;
my $jardir = $type eq 'install' ? File::Spec->catfile($^O eq 'MSWin32' ? $static_rakudo_home : '${RAKUDO_HOME}', 'runtime') : $prefix;
my $libdir = $type eq 'install' ? File::Spec->catfile($^O eq 'MSWin32' ? $static_rakudo_home : '${RAKUDO_HOME}', 'lib') : 'blib';
my $sharedir = File::Spec->catfile(
    ($type eq 'install' && $^O ne 'MSWin32' ? '${RAKUDO_HOME}' : File::Spec->catfile($prefix, 'share', 'perl6') ),
    'site', 'lib');
my $rakudo_jars = join( $cpsep,
    $^O eq 'MSWin32' ? $nqpjars : '${NQP_JARS}',
    File::Spec->catfile($jardir, 'rakudo-runtime.jar'),
    File::Spec->catfile($jardir, $debugger ? 'rakudo-debug.jar' : 'rakudo.jar'));

my $NQP_LIB = $type eq 'install' ? '' : ': ${NQP_LIB:="blib"}';

my $preamble_unix = <<'EOS';
#!/bin/sh

# Sourced from https://stackoverflow.com/a/29835459/1975049
rreadlink() (
  target=$1 fname= targetDir= CDPATH=
  { \unalias command; \unset -f command; } >/dev/null 2>&1
  [ -n "$ZSH_VERSION" ] && options[POSIX_BUILTINS]=on
  while :; do
      [ -L "$target" ] || [ -e "$target" ] || { command printf '%s\n' "ERROR: '$target' does not exist." >&2; return 1; }
      command cd "$(command dirname -- "$target")"
      fname=$(command basename -- "$target")
      [ "$fname" = '/' ] && fname=''
      if [ -L "$fname" ]; then
        target=$(command ls -l "$fname")
        target=${target#* -> }
        continue
      fi
      break
  done
  targetDir=$(command pwd -P)
  if [ "$fname" = '.' ]; then
    command printf '%s\n' "${targetDir%/}"
  elif  [ "$fname" = '..' ]; then
    command printf '%s\n' "$(command dirname -- "${targetDir}")"
  else
    command printf '%s\n' "${targetDir%/}/$fname"
  fi
)

EXEC=$(rreadlink "$0")
DIR=$(dirname -- "$EXEC")

EOS

my $preamble;
if ($^O eq 'MSWin32') {
    $preamble = '@';
}
elsif ($type eq 'install') {
    if ($relocatable) {
        $preamble = join("\n",
            $preamble_unix,
            ": \${NQP_HOME:=\"\$DIR/../share/nqp\"}",
            ": \${NQP_JARS:=\"$nqpjars\"}",
            ": \${RAKUDO_HOME:=\"\$PERL6_HOME\"}",
            ": \${RAKUDO_HOME:=\"\$DIR/../share/perl6\"}",
            ": \${RAKUDO_JARS:=\"$rakudo_jars\"}",
            "exec "
        );
    }
    else {
        $preamble = join("\n",
            $preamble_unix,
            ": \${NQP_HOME:=\"$static_nqp_home\"}",
            ": \${NQP_JARS:=\"$nqpjars\"}",
            ": \${RAKUDO_HOME:=\"\$PERL6_HOME\"}",
            ": \${RAKUDO_HOME:=\"$static_rakudo_home\"}",
            ": \${RAKUDO_JARS:=\"$rakudo_jars\"}",
            "exec "
        );
    }
}
else {
    # Hack: Explicitly set a dummy RAKUDO_HOME, so the autogenerated
    # CompUnitRepo folder structure does not end up in the build directories
    # parent folder.
    my $rakudo_home = "$basedir/gen/build_rakudo_home";

    # When building against the in-tree Gradle-built nqp (no installed
    # nqp-j), the configured nqp home points at the would-be install
    # prefix; fall back to the nested checkout's build output so
    # ${NQP_HOME}/lib resolves ModuleLoader.jar and friends.
    if (!-e "$nqp_home/lib/ModuleLoader.jar"
        && -e "$basedir/nqp/build/jvm/share/lib/ModuleLoader.jar") {
        $nqp_home = "$basedir/nqp/build/jvm/share";
    }

    $preamble = join("\n",
        $preamble_unix,
        "$NQP_LIB",
        "NQP_HOME=\"$nqp_home\"",
        ": \${NQP_JARS:=\"$nqpjars\"}",
        "RAKUDO_HOME=\"$rakudo_home\"",
        ": \${RAKUDO_JARS:=\"$rakudo_jars\"}",
        "exec "
    );
}

my $postamble = $^O eq 'MSWin32' ? ' %*' : ' "$@"';

sub install {
    my ($name, $command, $guard) = @_;

    # A guard is shell that runs before the exec (Unix only; the Windows
    # preamble is a bare '@' and has nothing to guard with).
    my $pre = $preamble;
    $pre =~ s/exec $/$guard\nexec / if defined $guard && $^O ne 'MSWin32';

    my $install_to = $destdir
        ? File::Spec->catfile($destdir, $bindir, "$name$bat")
        : File::Spec->catfile($bindir, "$name$bat");

    #print "Creating '$install_to'\n";
    open my $fh, ">", $install_to or die "open: $!";
    print $fh $pre, $command, $postamble, "\n" or die "print: $!";
    close $fh or die "close: $!";

    chmod 0755, $install_to if $^O ne 'MSWin32';
}

# The grammar engine. nqp.jar carries rules compiled to Truffle descriptors,
# and a JVM that loads it without these cannot run them at all: the modules
# have to be on the MODULE path (Truffle binds to the JDK's compiler only as
# modules) and the engine on the class path (the boot loader cannot see the
# module path). An nqp built without the engine has no truffle directory and
# the flags stay empty, which is the old behaviour exactly.
my $truffle_opts = '';
my $engine_cp    = '';
if (-d File::Spec->catfile($nqp_home, 'truffle')) {
    my $mp = $^O eq 'MSWin32' ? File::Spec->catfile($static_nqp_home, 'truffle')
                              : '${NQP_HOME}/truffle';
    my $en = $^O eq 'MSWin32'
           ? File::Spec->catfile($static_nqp_home, 'runtime', 'nqp-truffle.jar')
           : '${NQP_HOME}/runtime/nqp-truffle.jar';
    # --enable-native-access names the MODULE: Truffle is a named module, so
    # the ALL-UNNAMED grant below does not reach it and the JVM says so on
    # every run. Repeating the flag accumulates rather than replaces.
    #
    # --sun-misc-unsafe-memory-access: truffle-runtime calls the terminally
    # deprecated Unsafe::objectFieldOffset. Nothing here can fix that, and
    # the noise is not harmless -- these lines land on stderr ahead of a
    # compiler's own output, which broke a test asserting on the first line
    # of it (nqp's t/nqp/114-pod-panic.t).
    $truffle_opts = " --module-path $mp"
                  . " --add-modules org.graalvm.truffle,org.graalvm.truffle.runtime"
                  . " --enable-native-access=org.graalvm.truffle"
                  . " --sun-misc-unsafe-memory-access=allow";
    $engine_cp    = $cpsep . $en;
}

my $classpath = join($cpsep, ($rakudo_jars, $jardir, $libdir, $nqplibdir)) . $engine_cp;
# The RakuAST frontend walks deeply nested ASTs (VarLowering's
# IMPL-WALK recurses once per node), and the JVM's default main-thread
# stack overflows on a file the size of the core setting. MoarVM grows
# its stack on demand; here it has to be asked for up front.
# Do not add -noverify back: it has been a no-op since JDK 13, and warns.
my $jopts = '-Xms100m -Xss512m --enable-native-access=ALL-UNNAMED'
          . $truffle_opts
          . ' -cp ' . ($^O eq 'MSWin32' ? '"%CLASSPATH%";' : '$CLASSPATH:') . $classpath
          . ' -Dperl6.prefix=' . ($type eq 'install' && $^O ne 'MSWin32' ? '$DIR/..' : $prefix)
          . ' -Dnqp.library.path=' . $sharedir
          . ($^O eq 'MSWin32' ? ' -Dperl6.execname="%~dpf0"' : ' -Dperl6.execname="$EXEC"');
my $jdbopts = '-Xdebug -Xrunjdwp:transport=dt_socket,address=' 
            . ($^O eq 'MSWin32' ? '8000' : '${RAKUDO_JDB_PORT:=8000}') 
            . ',server=y,suspend=y';

if ($debugger) {
    install "rakudo-debug-j", "java $jopts rakudo-debug";
    install "perl6-debug-j", "java $jopts rakudo-debug";
}
else {
    install "rakudo-j", "java $jopts perl6";
    install "perl6-j", "java $jopts perl6";
    install "rakudo-jdb-server", "java $jdbopts $jopts perl6";
    install "perl6-jdb-server", "java $jdbopts $jopts perl6";
    # The server keeps one JVM for many runs, and each run builds a whole
    # GlobalContext with its own copy of the setting. Several of those are live
    # at once before the collector catches up, so 3000m runs out after a
    # handful of runs -- as an OutOfMemoryError from whichever run happened to
    # be unlucky, which reads as a broken test rather than a full heap.
    # The ceiling stays overridable: a pool of servers must divide the
    # machine's memory between them, and only the pool runner knows how many
    # of them there are.
    my $esheap = $^O eq 'MSWin32' ? '8g' : '${RAKUDO_EVALSERVER_HEAP:=8g}';

    # The memory guard. Several servers at once have twice taken this
    # machine down (2026-08-31, 2026-09-02): the kernel OOM killer fires
    # late on a swapless box, picks the biggest JVM, and the terminal's
    # whole cgroup goes with it. Advice in docs did not prevent the second
    # time, so the arithmetic lives here, where every launcher passes:
    #
    #  - refuse to start when this server's ceiling plus the room every
    #    live server can still grow into does not fit in MemAvailable;
    #  - run the JVM in its own systemd scope capped at that ceiling, so a
    #    runaway is killed by itself and nothing else is.
    #
    # A server's ceiling is its heap plus ~2g the JVM keeps outside it
    # (512m thread stacks, metaspace, Truffle code cache): the server shot
    # on 2026-09-02 held 8.7g against an 8g heap. systemd-run --scope
    # execs the command in place, so the pid a caller gets is java's own
    # and pipes/kills behave exactly as before.
    my $guard = <<'GUARD';

# Memory guard: see the comment above the eval-server runners in
# tools/build/create-jvm-runner.pl. Do not bypass it -- lower
# RAKUDO_EVALSERVER_HEAP or stop a server instead.
heap="${RAKUDO_EVALSERVER_HEAP:=8g}"
mb_of() { case "$1" in *[gG]) echo $(( ${1%[gG]} * 1024 )) ;; *[mM]) echo "${1%[mM]}" ;; *[kK]) echo $(( ${1%[kK]} / 1024 )) ;; *) echo $(( $1 / 1048576 )) ;; esac; }
OVERHEAD_MB=2048
need=$(( $(mb_of "$heap") + OVERHEAD_MB ))
if [ -r /proc/meminfo ]; then
    avail=$(awk '/^MemAvailable:/ { print int($2 / 1024) }' /proc/meminfo)
    live=0; grow=0
    for pid in $(pgrep -f 'org\.raku\.nqp\.tools\.EvalServer' 2>/dev/null); do
        xmx=$(tr '\0' ' ' < /proc/$pid/cmdline 2>/dev/null | sed -n 's/.*-Xmx\([0-9]*[gGmMkK]\{0,1\}\) .*/\1/p')
        [ -n "$xmx" ] || continue
        rss=$(awk '/^VmRSS:/ { print int($2 / 1024) }' /proc/$pid/status 2>/dev/null)
        room=$(( $(mb_of "$xmx") + OVERHEAD_MB - ${rss:-0} ))
        [ "$room" -gt 0 ] && grow=$(( grow + room ))
        live=$(( live + 1 ))
    done
    if [ $(( need + grow )) -gt "$avail" ]; then
        echo "rakudo-eval-server: REFUSING to start." >&2
        echo "  this server may grow to ${need}m (heap $heap + ${OVERHEAD_MB}m off-heap)," >&2
        echo "  the $live live server(s) may still grow by ${grow}m, MemAvailable is ${avail}m." >&2
        echo "  Stop a server or set RAKUDO_EVALSERVER_HEAP lower. Do not work around this check." >&2
        exit 75
    fi
fi
cage=""
if command -v systemd-run >/dev/null 2>&1 && systemd-run --user --scope --quiet -- true >/dev/null 2>&1; then
    cage="systemd-run --user --scope --quiet -p MemoryMax=${need}M --"
fi
GUARD
    my $caged = $^O eq 'MSWin32' ? '' : '$cage ';
    install "rakudo-eval-server", "${caged}java -Xmx$esheap $jopts org.raku.nqp.tools.EvalServer", $guard;
    install "perl6-eval-server", "${caged}java -Xmx$esheap $jopts org.raku.nqp.tools.EvalServer", $guard;
}

